/* ==========================================================================
   ATHA — online box breathing timer
   Progressive enhancement over a static block: without JavaScript the inner
   square keeps breathing 4-4-4-4 (CSS) and the page lists the exact timings.
   Runs entirely in the browser. No storage, no network, no tracking.

   The track is a rounded square and one lap is one box: in goes up the left
   side, hold across the top, out down the right, hold along the bottom. A
   side whose phase is 0 s belongs to the phase before it, so 4-0-4-0 breathes
   in up the left and over the top. The square inside grows on the in-breath,
   waits, shrinks on the out-breath and waits again. Only the countdown digit
   (or a play / check glyph) sits inside it; words live below the stage.

   Markup (generated by tools/build-box-timer.py):
     [data-box-timer]            root; gets .is-ready, .is-focus, data-state
     svg [data-bt-track]         path from the bottom-left corner, clockwise
         [data-bt-progress] [data-bt-dot] [data-bt-orb]
     [data-bt-stage]             tap target over the square (toggles)
     [data-bt-count] [data-bt-phase] [data-bt-status] [data-bt-timeline]
     [data-bt-toggle] [data-bt-reset] [data-bt-focus]
     [data-bt-patterns] / [data-bt-lengths]  segmented controls (radios)
     [data-bt-sound] [data-bt-vibrate]       switches
     [data-bt-done] [data-bt-done-count] [data-bt-controls]
   Options: data-no-url (don't touch the address bar), data-share-url.
   URL presets: ?pattern=4-4-4-4&min=2 (min=0 runs until you stop).
   Share/embed helpers: [data-bt-copy], [data-bt-share], [data-bt-copy-embed].
   ========================================================================== */
(function () {
  'use strict';

  // Copy follows the page language (<html lang="tr"> gets Turkish).
  var TR = document.documentElement.lang === 'tr';
  var L = TR ? {
    labels: ['Nefes al', 'Tut', 'Nefes ver', 'Boş tut'], sides: ['Al', 'Tut', 'Ver', 'Boş tut'],
    ready: 'Hazır olduğunda başla', paused: 'Duraklatıldı', lead: 'Nefesini tamamen ver', done: 'Bitti',
    buttons: { idle: 'Başlat', running: 'Duraklat', paused: 'Devam et', done: 'Yeniden başlat' },
    hidden: 'Sayfa arka plana geçince duraklatıldı.',
    full: 'Tam ekran', exitFull: 'Tam ekrandan çık', copied: 'Kopyalandı.', sec: 'sn',
    boxes: function (n) { return n + ' kutu'; },
    plan: function (n, cycle, time) { return n + ' kutu · ' + time + ' · kutu başına ' + cycle + ' sn'; },
    open: function (cycle) { return 'Süresiz · kutu başına ' + cycle + ' sn'; },
    starting: 'Başlıyor…',
    progress: function (box, of, left) { return 'Kutu ' + box + '/' + of + ' · ' + left + ' kaldı'; },
    progressOpen: function (box, time) { return 'Kutu ' + box + ' · ' + time; },
    finished: function (n, time) { return time + ' içinde ' + n + ' kutu'; },
    shareTitle: 'Kutu nefesi zamanlayıcı', shareText: 'Tarayıcıda çalışan ücretsiz 4-4-4-4 kutu nefesi zamanlayıcı.'
  } : {
    labels: ['Breathe in', 'Hold', 'Breathe out', 'Hold'], sides: ['In', 'Hold', 'Out', 'Hold'],
    ready: 'Start when you’re ready', paused: 'Paused', lead: 'Breathe out fully', done: 'Done',
    buttons: { idle: 'Start', running: 'Pause', paused: 'Resume', done: 'Start again' },
    hidden: 'Paused while the page was hidden.',
    full: 'Full screen', exitFull: 'Exit full screen', copied: 'Copied.', sec: 's',
    boxes: function (n) { return n + (n === 1 ? ' box' : ' boxes'); },
    plan: function (n, cycle, time) { return n + (n === 1 ? ' box' : ' boxes') + ' · ' + time + ' · ' + cycle + ' s each'; },
    open: function (cycle) { return 'No time limit · ' + cycle + ' s a box'; },
    starting: 'Starting…',
    progress: function (box, of, left) { return 'Box ' + box + ' of ' + of + ' · ' + left + ' left'; },
    progressOpen: function (box, time) { return 'Box ' + box + ' · ' + time; },
    finished: function (n, time) { return n + (n === 1 ? ' box' : ' boxes') + ' in ' + time; },
    shareTitle: 'Box breathing timer', shareText: 'A free 4-4-4-4 box breathing timer that runs in the browser.'
  };
  var TONES = [528, 660, 396, 330];
  var LEAD = 3;            // seconds of "breathe out fully" before the first box
  var ORB_MIN = 0.55;
  var ORB_MAX = 1;
  var ORB_REST = 0.78;     // size under Reduce Motion

  function reducedMotion() {
    return !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
  }

  function parsePattern(text) {
    var parts = String(text || '').split(/[,\-\s]+/);
    if (parts.length !== 4) { return null; }
    var out = [];
    for (var i = 0; i < 4; i++) {
      var n = parseFloat(parts[i]);
      if (!isFinite(n) || n < 0 || n > 20) { return null; }
      out.push(Math.round(n * 2) / 2);
    }
    return out[0] > 0 && out[2] > 0 ? out : null;
  }

  function fmt(seconds) {
    seconds = Math.max(0, Math.ceil(seconds));
    var m = Math.floor(seconds / 60);
    var s = seconds % 60;
    return m + ':' + (s < 10 ? '0' : '') + s;
  }

  function ease(t) { return 0.5 - 0.5 * Math.cos(Math.PI * Math.max(0, Math.min(1, t))); }

  function checked(group) {
    return group ? group.querySelector('input[type="radio"]:checked') : null;
  }

  /* ---- segmented control: a thumb that slides to the checked option ------ */

  function Segmented(group, onChange) {
    this.group = group;
    this.thumb = group.querySelector('.atha-seg__thumb');
    var self = this;
    group.addEventListener('change', function () { self.place(true); onChange(); });
    if (window.ResizeObserver) { new window.ResizeObserver(function () { self.place(false); }).observe(group); }
    this.place(false);
  }

  Segmented.prototype.place = function (animate) {
    var input = checked(this.group);
    if (!this.thumb || !input) { return; }
    var opt = input.closest('.atha-seg__opt');
    if (!opt || !opt.offsetWidth) { return; }
    if (!animate) { this.thumb.style.transition = 'none'; }
    this.thumb.style.width = opt.offsetWidth + 'px';
    this.thumb.style.transform = 'translateX(' + opt.offsetLeft + 'px)';
    if (!animate) { void this.thumb.offsetWidth; this.thumb.style.transition = ''; }
    this.group.classList.add('has-thumb');
  };

  /* ---- timer -------------------------------------------------------------- */

  function Timer(root) {
    this.root = root;
    var q = function (sel) { return root.querySelector(sel); };
    this.track = q('[data-bt-track]');
    this.progress = q('[data-bt-progress]');
    this.dot = q('[data-bt-dot]');
    this.orb = q('[data-bt-orb]');
    this.phaseEl = q('[data-bt-phase]');
    this.countEl = q('[data-bt-count]');
    this.statusEl = q('[data-bt-status]');
    this.timeline = q('[data-bt-timeline]');
    this.toggleBtn = q('[data-bt-toggle]');
    this.resetBtn = q('[data-bt-reset]');
    this.focusBtn = q('[data-bt-focus]');
    this.stageBtn = q('[data-bt-stage]');
    this.patterns = q('[data-bt-patterns]');
    this.lengths = q('[data-bt-lengths]');
    this.soundBox = q('[data-bt-sound]');
    this.vibrateBox = q('[data-bt-vibrate]');
    this.doneEl = q('[data-bt-done]');
    this.state = 'idle';
    this.elapsed = 0;
    this.raf = 0;
    this.audio = null;
    this.wakeLock = null;
    this.lastKey = '';

    var self = this;
    this.readURL();
    this.pattern = parsePattern(checked(this.patterns) && checked(this.patterns).value) || [4, 4, 4, 4];

    if (this.patterns) {
      this.patternSeg = new Segmented(this.patterns, function () {
        self.pattern = parsePattern(checked(self.patterns).value) || [4, 4, 4, 4];
        self.reset();
        self.syncURL();
      });
    }
    if (this.lengths) {
      this.lengthSeg = new Segmented(this.lengths, function () { self.reset(); self.syncURL(); });
    }
    this.toggleBtn.addEventListener('click', function () { self.toggle(); });
    if (this.stageBtn) { this.stageBtn.addEventListener('click', function () { self.toggle(); }); }
    if (this.resetBtn) { this.resetBtn.addEventListener('click', function () { self.reset(); }); }
    if (this.focusBtn) { this.focusBtn.addEventListener('click', function () { self.setFocus(!root.classList.contains('is-focus')); }); }
    if (this.soundBox) { this.soundBox.addEventListener('change', function () { if (self.soundBox.checked) { self.tone(TONES[0]); } }); }
    if (this.vibrateBox) {
      var row = this.vibrateBox.closest('[data-bt-vibrate-row]');
      // Only phones buzz; desktop browsers expose vibrate() but do nothing with it.
      var touch = window.matchMedia && window.matchMedia('(pointer: coarse)').matches;
      if (navigator.vibrate && touch) { if (row) { row.hidden = false; } } else { this.vibrateBox = null; }
    }

    document.addEventListener('visibilitychange', function () {
      if (document.hidden && self.state === 'running') { self.pause(L.hidden); }
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && root.classList.contains('is-focus')) { self.setFocus(false); return; }
      if (e.key !== ' ' && e.code !== 'Space') { return; }
      var tag = (e.target && e.target.tagName) || '';
      if (/^(INPUT|SELECT|TEXTAREA|BUTTON|A|SUMMARY)$/.test(tag)) { return; }
      e.preventDefault();
      self.toggle();
    });

    var controls = q('[data-bt-controls]');
    if (controls) { controls.hidden = false; }
    root.classList.add('is-ready');
    this.idle();
    // Thumbs measure their options, so place them again once layout settles.
    window.requestAnimationFrame(function () {
      if (self.patternSeg) { self.patternSeg.place(false); }
      if (self.lengthSeg) { self.lengthSeg.place(false); }
    });
  }

  /* ---- settings ---------------------------------------------------------- */

  // ?pattern=5-5-5-5&min=3 picks a preset; an unlisted pattern gets its own option.
  Timer.prototype.readURL = function () {
    var params;
    try { params = new URLSearchParams(window.location.search); } catch (e) { return; }
    var p = parsePattern(params.get('pattern'));
    if (p && this.patterns) {
      var key = p.join(',');
      var input = this.patterns.querySelector('input[value="' + key + '"]');
      if (!input) {
        var opt = document.createElement('label');
        opt.className = 'atha-seg__opt atha-seg__opt--custom';
        input = document.createElement('input');
        input.type = 'radio';
        input.name = (this.patterns.querySelector('input') || {}).name || 'bt-pattern';
        input.value = key;
        var span = document.createElement('span');
        span.textContent = p.join('-');
        opt.appendChild(input);
        opt.appendChild(span);
        this.patterns.appendChild(opt);
      }
      input.checked = true;
    }
    var min = params.get('min');
    if (min !== null && this.lengths) {
      var secs = String(Math.round(parseFloat(min) * 60));
      var len = this.lengths.querySelector('input[value="' + secs + '"]');
      if (len) { len.checked = true; }
    }
  };

  Timer.prototype.lengthSeconds = function () {
    var input = checked(this.lengths);
    return input ? parseInt(input.value, 10) : 120;
  };

  Timer.prototype.shareURL = function () {
    var base = this.root.getAttribute('data-share-url') || (window.location.origin + window.location.pathname);
    return base + '?pattern=' + this.pattern.join('-') + '&min=' + (this.lengthSeconds() / 60);
  };

  Timer.prototype.syncURL = function () {
    if (this.root.hasAttribute('data-no-url') || !window.history || !window.history.replaceState) { return; }
    try {
      var url = this.shareURL();
      window.history.replaceState(null, '', url.slice(url.indexOf('?')));
    } catch (e) { /* optional */ }
  };

  Timer.prototype.cycle = function () {
    return this.pattern[0] + this.pattern[1] + this.pattern[2] + this.pattern[3];
  };

  Timer.prototype.totalFor = function () {
    var wanted = this.lengthSeconds();
    if (!wanted) { return Infinity; }
    // Always finish on a complete box.
    return Math.max(1, Math.round(wanted / this.cycle())) * this.cycle();
  };

  /* ---- drawing ----------------------------------------------------------- */

  // Each phase owns its side plus any 0 s sides after it: spans[i] is the
  // stretch of the lap (0-1) the dot covers during phase i. The timeline
  // below the stage gets one segment per phase, as wide as its seconds.
  Timer.prototype.build = function () {
    this.spans = [];
    this.segs = [];
    if (this.timeline) { this.timeline.textContent = ''; }
    for (var i = 0; i < 4; i++) {
      var len = this.pattern[i];
      if (len <= 0) { this.spans.push(null); continue; }
      var next = i + 1;
      while (next < 4 && this.pattern[next] <= 0) { next++; }
      this.spans.push({ from: i / 4, to: next / 4 });
      if (!this.timeline) { continue; }
      var li = document.createElement('li');
      li.className = 'atha-boxtimer__seg';
      li.style.flexGrow = String(len);
      li.innerHTML = '<span class="atha-boxtimer__segbar"><span class="atha-boxtimer__segfill"></span></span>' +
        '<span class="atha-boxtimer__seglabel"></span>';
      li.lastChild.textContent = L.sides[i] + ' ';
      var n = document.createElement('span');
      n.className = 'atha-boxtimer__segsec';
      n.textContent = len + ' ' + L.sec;
      li.lastChild.appendChild(n);
      this.timeline.appendChild(li);
      this.segs.push({ phase: i, li: li, fill: li.firstChild.firstChild });
    }
  };

  Timer.prototype.setTimeline = function (phase, into) {
    (this.segs || []).forEach(function (seg) {
      var v = phase < 0 ? 0 : seg.phase < phase ? 1 : seg.phase === phase ? into : 0;
      seg.fill.style.transform = 'scaleX(' + v.toFixed(4) + ')';
      seg.li.classList.toggle('is-current', seg.phase === phase);
    });
  };

  // A point on the track, `fraction` of the way round from the bottom-left corner.
  Timer.prototype.pointAt = function (fraction) {
    try {
      if (!this.trackLength) { this.trackLength = this.track.getTotalLength(); }
      return this.track.getPointAtLength((fraction % 1) * this.trackLength);
    } catch (e) { return null; }
  };

  Timer.prototype.setRing = function (fraction) {
    this.progress.setAttribute('stroke-dasharray', (fraction * 100).toFixed(3) + ' 100');
    var p = this.pointAt(fraction);
    if (!p) { return; }
    this.dot.setAttribute('cx', p.x.toFixed(2));
    this.dot.setAttribute('cy', p.y.toFixed(2));
  };

  // scale drives the inner square; --bt-breath (0-1) drives its glow.
  Timer.prototype.setOrb = function (scale) {
    if (!this.orb) { return; }
    if (reducedMotion()) { scale = ORB_REST; }
    this.orb.style.transform = 'scale(' + scale.toFixed(4) + ')';
    this.orb.style.setProperty('--bt-breath', ((scale - ORB_MIN) / (ORB_MAX - ORB_MIN)).toFixed(3));
  };

  // Inside the square: a number, or a glyph (play / check) when there's none.
  Timer.prototype.setCenter = function (text, glyph) {
    this.countEl.textContent = text || '';
    this.root.setAttribute('data-glyph', glyph || '');
  };

  // Phase words fade in once the user has started; the first render stays still.
  Timer.prototype.setPhase = function (text) {
    if (this.phaseEl.textContent === text) { return; }
    this.phaseEl.textContent = text;
    if (!this.touched) { return; }
    this.phaseEl.classList.remove('is-new');
    void this.phaseEl.offsetWidth;
    this.phaseEl.classList.add('is-new');
  };

  /* ---- states ------------------------------------------------------------ */

  Timer.prototype.setState = function (state) {
    this.state = state;
    this.root.setAttribute('data-state', state);
    var label = L.buttons[state];
    this.toggleBtn.textContent = label;
    this.toggleBtn.setAttribute('aria-pressed', state === 'running' ? 'true' : 'false');
    if (this.stageBtn) { this.stageBtn.setAttribute('aria-label', label); }
    if (this.resetBtn) { this.resetBtn.hidden = !(state === 'running' || state === 'paused'); }
  };

  Timer.prototype.idle = function () {
    this.stopLoop();
    this.setState('idle');
    this.elapsed = 0;
    this.build();
    this.setRing(0);
    this.setOrb(ORB_MIN);
    this.setTimeline(-1, 0);
    this.setPhase(L.ready);
    this.setCenter('', 'play');
    var total = this.totalFor();
    this.statusEl.textContent = isFinite(total)
      ? L.plan(Math.round(total / this.cycle()), this.cycle(), fmt(total))
      : L.open(this.cycle());
    if (this.doneEl) { this.doneEl.hidden = true; }
  };

  Timer.prototype.toggle = function () {
    if (this.state === 'running') { this.pause(); return; }
    if (this.state === 'paused') { this.resume(); return; }
    this.begin();
  };

  Timer.prototype.begin = function () {
    this.touched = true;
    this.stopLoop();
    this.total = this.totalFor();
    this.elapsed = 0;
    if (this.doneEl) { this.doneEl.hidden = true; }
    this.resume();
  };

  Timer.prototype.resume = function () {
    this.setState('running');
    this.since = performance.now();
    this.base = this.elapsed;
    this.lastKey = '';
    // Create the audio context inside the click, so iOS Safari allows it.
    if (this.soundBox && this.soundBox.checked) { this.tone(0); }
    this.lockScreen(true);
    var self = this;
    var loop = function () {
      if (self.state !== 'running') { return; }
      self.tick();
      self.raf = window.requestAnimationFrame(loop);
    };
    this.raf = window.requestAnimationFrame(loop);
  };

  Timer.prototype.pause = function (message) {
    if (this.state !== 'running') { return; }
    this.tick();
    if (this.state !== 'running') { return; }   // the session ended during that tick
    this.stopLoop();
    this.setState('paused');
    this.lockScreen(false);
    this.setPhase(L.paused);
    this.setCenter('', 'play');
    if (message) { this.statusEl.textContent = message; }
  };

  Timer.prototype.reset = function () {
    this.lockScreen(false);
    this.idle();
  };

  Timer.prototype.stopLoop = function () {
    if (this.raf) { window.cancelAnimationFrame(this.raf); this.raf = 0; }
  };

  Timer.prototype.tick = function () {
    this.elapsed = this.base + (performance.now() - this.since) / 1000;
    var t = this.elapsed;

    if (t < LEAD) {
      var k = 'lead' + Math.ceil(LEAD - t);
      if (k !== this.lastKey) {
        this.lastKey = k;
        this.setPhase(L.lead);
        this.setCenter(String(Math.ceil(LEAD - t)), '');
        this.statusEl.textContent = L.starting;
        this.setTimeline(-1, 0);
      }
      this.setOrb(ORB_MIN + (ORB_MAX - ORB_MIN) * 0.25 * (1 - ease(t / LEAD)));
      this.setRing(0);
      return;
    }

    var s = t - LEAD;
    if (s >= this.total) { this.finish(); return; }
    var cycle = this.cycle();
    var box = Math.floor(s / cycle);
    var inBox = s - box * cycle;
    var acc = 0;
    var phase = 0;
    for (var i = 0; i < 4; i++) {
      if (this.pattern[i] <= 0) { continue; }
      if (inBox < acc + this.pattern[i]) { phase = i; break; }
      acc += this.pattern[i];
    }
    var len = this.pattern[phase];
    var into = (inBox - acc) / len;
    var left = Math.ceil(acc + len - inBox);

    var span = this.spans[phase];
    this.setRing(span.from + (span.to - span.from) * into);
    this.setTimeline(phase, into);
    if (phase === 0) { this.setOrb(ORB_MIN + (ORB_MAX - ORB_MIN) * ease(into)); }
    else if (phase === 1) { this.setOrb(ORB_MAX); }
    else if (phase === 2) { this.setOrb(ORB_MAX - (ORB_MAX - ORB_MIN) * ease(into)); }
    else { this.setOrb(ORB_MIN); }

    var phaseKey = box + ':' + phase;
    if (this.lastKey.split('/')[0] !== phaseKey) {
      this.setPhase(L.labels[phase]);
      this.tone(TONES[phase]);
      this.buzz(phase);
    }
    var key = phaseKey + '/' + left;
    if (key !== this.lastKey) {
      this.lastKey = key;
      this.setCenter(String(left), '');
      this.statusEl.textContent = isFinite(this.total)
        ? L.progress(box + 1, Math.round(this.total / cycle), fmt(this.total - s))
        : L.progressOpen(box + 1, fmt(s));
    }
  };

  Timer.prototype.finish = function () {
    var boxes = Math.round(this.total / this.cycle());
    this.stopLoop();
    this.lockScreen(false);
    this.setState('done');
    this.setRing(0);
    this.setOrb(ORB_MIN);
    this.setTimeline(-1, 0);
    this.setPhase(L.done);
    this.setCenter('', 'check');
    this.statusEl.textContent = L.finished(boxes, fmt(this.total));
    this.tone(TONES[0]);
    if (this.doneEl) {
      var n = this.doneEl.querySelector('[data-bt-done-count]');
      if (n) { n.textContent = L.boxes(boxes); }
      this.doneEl.hidden = false;
    }
  };

  /* ---- extras ------------------------------------------------------------ */

  Timer.prototype.tone = function (freq) {
    if (!this.soundBox || !this.soundBox.checked) { return; }
    try {
      if (!this.audio) {
        var Ctx = window.AudioContext || window.webkitAudioContext;
        if (!Ctx) { return; }
        this.audio = new Ctx();
      }
      var ctx = this.audio;
      if (ctx.state === 'suspended') { ctx.resume(); }
      if (!freq) { return; }
      var osc = ctx.createOscillator();
      var gain = ctx.createGain();
      var now = ctx.currentTime;
      // Holds are a little quieter than the breaths.
      var peak = freq === TONES[1] || freq === TONES[3] ? 0.045 : 0.08;
      osc.type = 'sine';
      osc.frequency.value = freq;
      gain.gain.setValueAtTime(0.0001, now);
      gain.gain.exponentialRampToValueAtTime(peak, now + 0.06);
      gain.gain.exponentialRampToValueAtTime(0.0001, now + 0.9);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start(now);
      osc.stop(now + 1);
    } catch (e) { /* sound is optional */ }
  };

  Timer.prototype.buzz = function (phase) {
    if (!this.vibrateBox || !this.vibrateBox.checked) { return; }
    try { navigator.vibrate(phase === 0 || phase === 2 ? 60 : [25, 60, 25]); } catch (e) { /* optional */ }
  };

  // Keep the phone screen on while a session runs (where the browser allows it).
  Timer.prototype.lockScreen = function (on) {
    var self = this;
    if (on) {
      if (self.wakeLock || !navigator.wakeLock) { return; }
      navigator.wakeLock.request('screen').then(function (lock) {
        if (self.state === 'running') { self.wakeLock = lock; } else { lock.release(); }
      }).catch(function () { /* optional */ });
    } else if (self.wakeLock) {
      self.wakeLock.release().catch(function () {});
      self.wakeLock = null;
    }
  };

  Timer.prototype.setFocus = function (on) {
    this.root.classList.toggle('is-focus', on);
    document.documentElement.classList.toggle('atha-boxtimer-focus', on);
    if (this.focusBtn) {
      var label = on ? L.exitFull : L.full;
      this.focusBtn.setAttribute('aria-label', label);
      this.focusBtn.setAttribute('title', label);
      this.focusBtn.setAttribute('aria-pressed', on ? 'true' : 'false');
    }
    try {
      var doc = document.documentElement;
      if (on && doc.requestFullscreen && !document.fullscreenElement) { doc.requestFullscreen().catch(function () {}); }
      if (!on && document.fullscreenElement && document.exitFullscreen) { document.exitFullscreen().catch(function () {}); }
    } catch (e) { /* the CSS overlay is enough */ }
    this.toggleBtn.focus();
  };

  /* ---- share & embed ------------------------------------------------------ */

  function flash(el, text) {
    if (!el) { return; }
    el.textContent = text;
    window.clearTimeout(el._t);
    el._t = window.setTimeout(function () { el.textContent = ''; }, 2600);
  }

  function copy(text, status) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(function () { flash(status, L.copied); }, function () { flash(status, text); });
    } else {
      flash(status, text);
    }
  }

  function bindShare(timer) {
    var status = document.querySelector('[data-bt-share-status]');
    var copyBtn = document.querySelector('[data-bt-copy]');
    var shareBtn = document.querySelector('[data-bt-share]');
    var embedBtn = document.querySelector('[data-bt-copy-embed]');
    var embedCode = document.querySelector('[data-bt-embed-code]');
    if (copyBtn) { copyBtn.addEventListener('click', function () { copy(timer.shareURL(), status); }); }
    if (shareBtn && navigator.share) {
      shareBtn.hidden = false;
      shareBtn.addEventListener('click', function () {
        navigator.share({ title: L.shareTitle, text: L.shareText, url: timer.shareURL() }).catch(function () {});
      });
    }
    if (embedBtn && embedCode) {
      embedBtn.addEventListener('click', function () {
        embedCode.select();
        copy(embedCode.value, status);
      });
    }
  }

  function init() {
    var nodes = document.querySelectorAll('[data-box-timer]');
    var first = null;
    for (var i = 0; i < nodes.length; i++) {
      try { var t = new Timer(nodes[i]); first = first || t; } catch (e) { /* static fallback stays */ }
    }
    if (first) { bindShare(first); }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
